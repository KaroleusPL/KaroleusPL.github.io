function NewFolder(name){
    console.log("New folder: ", name)

    FolderSelection.innerHTML += `
        <button onclick="OpenFolder('${name}')"> ${name} </button>
    `
}

function NewAutoFolder(name, look_for,look_for_equal_to, is_tag){

    MusicFolders[name] = []
    
    if (!is_tag && look_for_equal_to == undefined){
        let keys = Object.keys(Music)

        for (let i=0; i<keys.length; i++){
            let key = keys[i]
            // console.log("key: ", key)

            if (look_for in Music[key]){
                MusicFolders[name].push(key)
            }
        }
    }
    else if (!is_tag){
        let keys = Object.keys(Music)

        for (let i=0; i<keys.length; i++){
            let key = keys[i]
            // console.log("key: ", key)

            if (look_for in Music[key] && Music[key][look_for] == look_for_equal_to){
                MusicFolders[name].push(key)
            }
        }
    }
    else {
        let keys = Object.keys(Music)

        for (let i=0; i<keys.length; i++){
            let key = keys[i]

            if ("tags" in Music[key]){
                let tags = Music[key]["tags"]

                if (tags.includes(look_for)){
                    MusicFolders[name].push(key)
                }
            }
        }

    }

    FolderSelection.innerHTML += `
        <button onclick="OpenFolder('${name}')"> ${name} </button>
    `
}

